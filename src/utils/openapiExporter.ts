import { MockProject } from "../types";

export function exportOpenApi(project: MockProject, hostUrl: string): string {
  const paths: Record<string, any> = {};

  project.endpoints.forEach((ep) => {
    const swaggerPath = ep.path.replace(/:([a-zA-Z0-9_]+)/g, "{$1}");
    if (!paths[swaggerPath]) {
      paths[swaggerPath] = {};
    }

    const methodLower = ep.method.toLowerCase();
    const parameters: any[] = [];

    // Path parameters
    const pathParamMatches = ep.path.match(/:([a-zA-Z0-9_]+)/g);
    if (pathParamMatches) {
      pathParamMatches.forEach((m) => {
        parameters.push({
          name: m.replace(":", ""),
          in: "path",
          required: true,
          schema: { type: "string" },
        });
      });
    }

    const operation: any = {
      summary: ep.description,
      description: `Mock endpoint generated by MockAI Studio for ${project.name}`,
      parameters: parameters.length > 0 ? parameters : undefined,
      responses: {
        "200": {
          description: "Successful mock response",
          content: {
            "application/json": {
              example: ep.responseSample || { message: "Success" },
            },
          },
        },
      },
    };

    if (ep.requestBodySample && ["post", "put", "patch"].includes(methodLower)) {
      operation.requestBody = {
        required: true,
        content: {
          "application/json": {
            example: ep.requestBodySample,
          },
        },
      };
    }

    paths[swaggerPath][methodLower] = operation;
  });

  const openApiDoc = {
    openapi: "3.0.0",
    info: {
      title: project.name,
      description: project.description,
      version: "1.0.0",
    },
    servers: [
      {
        url: `${hostUrl}/api/m/${project.id}`,
        description: "Live MockAI Server",
      },
    ],
    paths,
  };

  return JSON.stringify(openApiDoc, null, 2);
}
